#!/usr/bin/env python3
"""Collect exact matching Samsung SSP Android runtime files, READ-ONLY over ADB.

Place this kit inside the Nuxel repo containing NUXEL_SSP_CONTINUATION_PACK/
ssp_runtime_audit.py. This script makes NO writes to the handset. It runs only
`cat` on allowlisted /vendor, /system, /system_ext, /product, or /apex paths.
It refuses to mix vendor runtimes when lhd/lhd.conf differ from the acquired
reference hashes. It cannot extract compressed APEX packages or mount images.

Without --collect-readonly it only prints a plan and makes no ADB calls.
"""
from __future__ import annotations
import argparse
import collections
import hashlib
import importlib.util
import json
from pathlib import Path, PurePosixPath
import re
import shlex
import subprocess
import sys

MAX_SINGLE_FILE = 64*1024*1024
MAX_TOTAL = 160*1024*1024
MAX_OBJECTS = 192
ANCHORS = {
    "vendor/bin/hw/lhd": "packs/sensors/acquired/vendor-bin-hw-lhd",
    "vendor/etc/sensor/lhd.conf": "packs/sensors/acquired/vendor-etc-sensor-lhd.conf",
    "vendor/lib64/sensors.sensorhub.so": "packs/sensors/acquired/vendor-lib64-sensors.sensorhub.so",
    "vendor/lib64/hw/sensors.exynos9820.so": "packs/sensors/acquired/vendor-lib64-hw-sensors.exynos9820.so",
}
SEED_FILES = tuple(k for k in ANCHORS if k.endswith(("lhd", ".so")))
SUPPLEMENTAL_FILES = (
    "vendor/build.prop", "system/build.prop", "system/etc/prop.default",
    "system/etc/ld.config.txt", "system/etc/ld.config.29.txt",
    "system/etc/ld.config.vndk_lite.txt", "vendor/etc/ld.config.txt",
)
SEARCH_DIRS = (
    "vendor/lib64", "vendor/lib64/hw", "vendor/lib64/vndk", "vendor/lib64/vndk-sp",
    "vendor/lib64/vndk-29", "vendor/lib64/vndk-sp-29", "system/lib64",
    "system/lib64/vndk-29", "system/lib64/vndk-sp-29", "system/lib64/vndk",
    "system/lib64/vndk-sp", "system_ext/lib64", "product/lib64",
    "apex/com.android.runtime/lib64/bionic", "apex/com.android.runtime/lib64",
)


def valid_relative(rel: str) -> bool:
    p = PurePosixPath(rel)
    return (bool(rel) and not p.is_absolute() and ".." not in p.parts
            and re.fullmatch(r"[a-zA-Z0-9_.+/@-]+", rel) is not None
            and p.parts[0] in {"vendor", "system", "system_ext", "product", "apex"})


def remote_candidates(rel: str) -> list[str]:
    if not valid_relative(rel):
        raise ValueError("invalid Android runtime path: " + rel)
    p = "/" + rel
    root = rel.split("/", 1)[0]
    candidates = [p]
    if root == "system":
        candidates += ["/system_root/" + rel, "/system/" + rel]
    elif root in {"vendor", "system_ext", "product"}:
        candidates += ["/system/" + rel, "/system_root/" + rel]
    elif root == "apex":
        # Mounted APEX, not an image; .apex files need a separate offline extraction.
        candidates += ["/system/" + rel]
    return list(dict.fromkeys(candidates))


def hashval(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def load_repo_elf(repo: Path):
    file = repo / "NUXEL_SSP_CONTINUATION_PACK/ssp_runtime_audit.py"
    if not file.is_file():
        raise FileNotFoundError(f"Required existing audit module missing: {file}")
    spec=importlib.util.spec_from_file_location("nuxel_ssp_existing_elf",file)
    mod=importlib.util.module_from_spec(spec)
    assert spec and spec.loader
    spec.loader.exec_module(mod)
    return mod.elf_meta


class AdbReader:
    """Read-only allowlisted remote fetch; stdout is binary, stderr separate."""
    def __init__(self, adb: str, serial: str|None, timeout: int = 12):
        self.prefix = [adb]+(["-s",serial] if serial else [])+["exec-out", "sh", "-c"]
        self.timeout = timeout
        self.requests = []

    def fetch(self, relative: str) -> tuple[bytes | None, str | None]:
        for remote in remote_candidates(relative):
            self.requests.append(remote)
            try:
                # Only cat. All paths are generated by valid_relative().
                p = subprocess.run(self.prefix + ["cat " + shlex.quote(remote)],
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                   timeout=self.timeout,check=False)
            except (OSError,subprocess.TimeoutExpired):
                continue
            if p.returncode == 0 and 0 < len(p.stdout) <= MAX_SINGLE_FILE:
                return p.stdout,remote
        return None,None


def extract_build_props(data: bytes) -> dict[str,str]:
    out={}
    for raw in data.decode("utf-8","replace").splitlines():
        if "=" not in raw or raw.startswith("#"):continue
        k,v=raw.split("=",1)
        if k in ("ro.build.fingerprint","ro.vendor.build.fingerprint",
                 "ro.build.version.sdk","ro.vendor.build.version.sdk",
                 "ro.product.vendor.device","ro.product.device","ro.build.version.release"):
            out[k]=v
    return out


def collect(repo: Path, out: Path, reader, elf_meta):
    """Only writes to a fresh HOST directory after matching vendor anchors."""
    expected={}
    for target, src in ANCHORS.items():
        b=(repo/src).read_bytes()
        expected[target]=hashval(b)
    artifacts={}; origins={}; discrepancies=[]
    # Fail closed on mismatched lhd / config / HAL. No mixed stock assets.
    for rel in ANCHORS:
        data,source=reader.fetch(rel)
        if data is None:
            raise RuntimeError(f"Vendor anchor unavailable: {rel} (verify TWRP read-only mounts)")
        if hashval(data)!=expected[rel]:
            raise RuntimeError(f"Vendor anchor MISMATCH {rel}: expected {expected[rel]}, got {hashval(data)}. Stop; identify exact build.")
        artifacts[rel]=data; origins[rel]=source
    loader,src=reader.fetch("system/bin/linker64")
    if loader is None:
        raise RuntimeError("Matching /system/bin/linker64 unavailable. This device/recovery may lack original Android system; provide owner-matched stock system image.")
    meta=elf_meta(loader)
    if not meta or meta.get("class")!=64 or meta.get("machine")!=183:
        raise RuntimeError("Retrieved linker64 is not AArch64 ELF64")
    artifacts["system/bin/linker64"]=loader; origins["system/bin/linker64"]=src

    queue=collections.deque(SEED_FILES)
    visited=set(); missing=[]; ambiguous=[]
    while queue:
        if len(visited)>=MAX_OBJECTS: raise RuntimeError("dependency walk exceeded file cap")
        rel=queue.popleft()
        if rel in visited:continue
        visited.add(rel)
        info=elf_meta(artifacts[rel]);
        if not info or info.get("class")!=64 or info.get("machine")!=183:
            raise RuntimeError(f"Non-AArch64 ELF64 in dependency chain: {rel}")
        for name in info.get("needed",[]):
            if not re.fullmatch(r"[a-zA-Z0-9_+.-]+\.so(?:\.[0-9]+)*",name):
                raise RuntimeError(f"Unexpected DT_NEEDED name {name!r} in {rel}")
            path=None
            # Same-directory dependencies first, then deterministic broad search.
            lookup=[str(PurePosixPath(rel).parent)+"/"+name]+[d+"/"+name for d in SEARCH_DIRS]
            for candidate in dict.fromkeys(lookup):
                if not valid_relative(candidate):continue
                if candidate in artifacts:
                    path=candidate;break
                b,remote=reader.fetch(candidate)
                if b is None:continue
                minfo=elf_meta(b)
                if not minfo or minfo.get("machine")!=183 or minfo.get("class")!=64:
                    discrepancies.append({"candidate":candidate,"required_by":rel,"reason":"wrong ELF format"})
                    continue
                if sum(map(len,artifacts.values())) + len(b)>MAX_TOTAL:
                    raise RuntimeError("runtime collection byte limit exceeded")
                artifacts[candidate]=b; origins[candidate]=remote
                path=candidate;break
            if path is None:
                missing.append({"required_by":rel,"library":name})
            else:
                queue.append(path)

    properties={}
    for rel in SUPPLEMENTAL_FILES:
        b,src=reader.fetch(rel)
        if b is not None and len(b)<=2_000_000:
            artifacts[rel]=b;origins[rel]=src
            if rel.endswith("build.prop") or rel.endswith("prop.default"):
                properties[rel]=extract_build_props(b)
    if out.exists():
        if out.is_symlink() or any(out.iterdir()):
            raise RuntimeError("refusing nonempty or symlink output directory")
    else:out.mkdir(parents=True)
    for rel,b in artifacts.items():
        path=out/rel
        path.parent.mkdir(parents=True,exist_ok=True)
        with path.open("xb") as f:f.write(b)
    result={"status":"STATIC_COLLECTION_ONLY" if not missing else "MISSING_DEPENDENCIES",
            "device_writes":0,"hardware_access":False,
            "warning":"Host runtime file collection is not permission to execute lhd or transmit firmware.",
            "origin_paths":origins,"properties":properties,"missing":missing,
            "invalid_candidates":discrepancies,
            "files":{rel:{"sha256":hashval(b),"bytes":len(b)} for rel,b in artifacts.items()}}
    (out/"ssp-stock-collection.json").write_text(json.dumps(result,indent=2,sort_keys=True)+"\n")
    return result


def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--repo-root",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    p.add_argument("--adb",default="adb")
    p.add_argument("--serial",help="explicit ADB device serial if more than one")
    p.add_argument("--collect-readonly",action="store_true",help="only read-only cat on approved Android partition paths")
    args=p.parse_args(argv)
    if not args.collect_readonly:
        print("PLAN ONLY — zero device calls. Mount matching Android system and vendor read-only in recovery.")
        print("Then re-run with --collect-readonly; output must be empty/new.")
        print("This cannot repair a missing stock system image, and it never flashes firmware.")
        return 0
    try:
        root=args.repo_root.resolve(strict=True)
        out=args.output.resolve()
        if out==root or out.is_relative_to(root):
            raise RuntimeError("output must be outside the repository")
        result=collect(root,out,AdbReader(args.adb,args.serial),load_repo_elf(root))
        print(json.dumps({"status":result["status"],"count":len(result["files"]),
                          "missing":len(result["missing"]),"output":str(out)},indent=2))
        return 0 if not result["missing"] else 3
    except (RuntimeError,OSError,ValueError,subprocess.SubprocessError) as exc:
        print("BLOCKED: "+str(exc),file=sys.stderr)
        return 4

if __name__=='__main__':
    raise SystemExit(main())
