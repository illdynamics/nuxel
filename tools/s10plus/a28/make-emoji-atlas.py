#!/usr/bin/env python3
"""make-emoji-atlas.py — rasterise the launcher's app-icon glyphs into an
embedded bitmap atlas for the S10+ framebuffer renderer.

WHY THIS FONT: pwa/nuxel-home/js/launcher.js renders each app icon as the emoji
from the registry, tinted with that app's own colour:

    '<div class="app-icon" style="background: '+app.color+'33; color: '+app.color+
    '"><span>'+app.icon+'</span></div>'

so a MONOCHROME emoji font is the correct source: the glyph is drawn in the
app colour (a colour-emoji font would ignore that colour).  Nothing is invented:
the codepoints come from tools/s10plus/a28/generated/nuxel-launcher.json, i.e.
straight out of pwa/nuxel-home/js/apps.js.

Font: Noto Emoji (OFL 1.1, Google) — vendored at
tools/s10plus/a28/assets/fonts/NotoEmoji[wght].ttf with its licence next to it.
Its sha256 is recorded in the generated file so the atlas cannot drift silently.

Usage: make-emoji-atlas.py [--out FILE] [--check]
Exit: 0 ok, 1 --check mismatch, 2 a required input is missing
"""
import argparse
import hashlib
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
FONT = os.path.join(HERE, "assets", "fonts", "NotoEmoji[wght].ttf")
REGISTRY_JSON = os.path.join(HERE, "generated", "nuxel-launcher.json")
DEFAULT_OUT = os.path.join(HERE, "generated", "nuxel-emoji-atlas.c")
ATLAS_SCALE = 4                      # the panel is 4x the 360x760 design space
SIZES = [24, 28]                     # launcher.css: dock 24px, grid 28px


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=FONT)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    if not os.path.exists(a.font):
        sys.exit("font not found: %s" % a.font)
    if not os.path.exists(REGISTRY_JSON):
        sys.exit("run gen-launcher.py first (%s missing)" % REGISTRY_JSON)

    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError:
        sys.exit("Pillow is required (pip install pillow)")

    reg = json.load(open(REGISTRY_JSON, encoding="utf-8"))
    cps = []
    for app in reg["apps"]:
        for c in app.get("icon_cp", []):
            if c and c not in cps:
                cps.append(c)
    if not cps:
        sys.exit("registry report carries no emoji codepoints")

    sizes = []
    for design_px in SIZES:
        px = design_px * ATLAS_SCALE
        f = ImageFont.truetype(a.font, px)
        glyphs = []
        for cp in cps:
            ch = chr(cp)
            bbox = f.getbbox(ch)
            if bbox is None or bbox[2] - bbox[0] <= 0 or bbox[3] - bbox[1] <= 0:
                sys.exit("font %s has no inked glyph for U+%04X" % (a.font, cp))
            l, t, r, b = bbox
            w, h = r - l, b - t
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=f, fill=255)
            cov = bytes((v >> 4) & 0xF for v in img.tobytes())
            packed = bytearray()
            for i in range(0, len(cov), 2):
                hi = cov[i]
                lo = cov[i + 1] if i + 1 < len(cov) else 0
                packed.append((hi << 4) | lo)
            glyphs.append(dict(cp=cp, w=w, h=h, bits=bytes(packed)))
        sizes.append(dict(design=design_px, px=px, glyphs=glyphs))

    bits = bytearray()
    tables = []
    for s in sizes:
        recs = []
        for g in s["glyphs"]:
            off = len(bits)
            bits += g["bits"]
            while len(bits) % 4:
                bits.append(0)
            recs.append((g["cp"], g["w"], g["h"], off))
        tables.append(recs)

    def carr(name, data, per=16):
        out = ["static const unsigned char %s[%d] = {" % (name, len(data))]
        for i in range(0, len(data), per):
            out.append("  " + ",".join("0x%02x" % b for b in data[i:i + per]) + ",")
        out.append("};")
        return "\n".join(out)

    L = []
    L.append("/* GENERATED by tools/s10plus/a28/make-emoji-atlas.py — do not edit." )
    L.append(" * Font: %s" % os.path.relpath(a.font, ROOT))
    L.append(" * sha256 %s" % hashlib.sha256(open(a.font, "rb").read()).hexdigest())
    L.append(" * Licence: SIL Open Font License 1.1 (see LICENSE-NotoEmoji.txt).")
    L.append(" * Glyphs: the emoji codepoints of pwa/nuxel-home/js/apps.js, so the")
    L.append(" * phone draws the launcher's OWN icons.  Monochrome by design: the")
    L.append(" * launcher tints them with each app's colour (launcher.js). */")
    L.append("#define NUXEL_EMOJI_ATLAS_SCALE %d" % ATLAS_SCALE)
    L.append("#define NUXEL_EMOJI_GLYPH_COUNT %d" % len(cps))
    L.append("#define NUXEL_EMOJI_NSIZES %d" % len(sizes))
    L.append("struct nuxel_emoji { unsigned int cp; unsigned short w,h; unsigned int off; };")
    L.append("struct nuxel_emoji_font { unsigned short design,px; unsigned int goff; };")
    L.append(carr("NUXEL_EMOJI_BITS", bytes(bits)))
    total_glyphs = 0
    for si, recs in enumerate(tables):
        L.append("static const struct nuxel_emoji NUXEL_EMOJI_%d[%d] = {"
                 % (sizes[si]["design"], len(recs)))
        for (cp, w, h, off) in recs:
            L.append("  { 0x%04Xu, %d, %d, %du }," % (cp, w, h, off))
        L.append("};")
        total_glyphs += len(recs)
    L.append("static const struct nuxel_emoji_font NUXEL_EMOJI_FONTS[NUXEL_EMOJI_NSIZES] = {")
    for si, s in enumerate(sizes):
        L.append("  { %d, %d, %du },   /* design %dpx -> %dpx atlas */"
                 % (s["design"], s["px"], 0, s["design"], s["px"]))
    L.append("};")
    L.append("static const struct nuxel_emoji *const NUXEL_EMOJI_TABLES[NUXEL_EMOJI_NSIZES] = {")
    for s in sizes:
        L.append("  NUXEL_EMOJI_%d," % s["design"])
    L.append("};")
    text = "\n".join(L) + "\n"

    out_path = a.out
    if a.check:
        cur = open(out_path, encoding="utf-8").read() if os.path.exists(out_path) else ""
        if cur != text:
            print("EMOJI_ATLAS_CHECK_FAILED: %s is stale" % os.path.relpath(out_path, ROOT),
                  file=sys.stderr)
            return 1
        print("EMOJI_ATLAS_CHECK_OK %s" % os.path.relpath(out_path, ROOT))
        return 0

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, "w", encoding="utf-8").write(text)
    print("EMOJI_ATLAS_OK codepoints=%d sizes=%s glyphs=%d bits=%d bytes out=%d bytes"
          % (len(cps), SIZES, total_glyphs, len(bits), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
