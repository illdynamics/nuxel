#!/usr/bin/env python3
"""gen-manifest.py — build firmware/s10plus/manifest.yml from the local blobs.

Reads every blob under firmware/s10plus/blobs/vendor-firmware/ and emits a
manifest with REAL sha256 checksums and a source_path that maps 1:1 onto the
blob tree (so firmware/s10plus/install-firmware.sh can install them).

Provenance: blobs are fetched by firmware/s10plus/fetch-vendor-blobs.sh from
Linux4/proprietary_vendor_samsung @ 05c9ef8f16e0ad5ab274e408c120dfd99fd5c628
(the pmaports vendor-blob source of record). Nothing is fabricated here.
"""
import hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
BLOBS = os.path.join(HERE, "blobs", "vendor-firmware")
OUT = os.path.join(HERE, "manifest.yml")

SRC = "Linux4/proprietary_vendor_samsung@05c9ef8f16e0ad5ab274e408c120dfd99fd5c628"

# category matchers (first match wins)
def category(name):
    n = name.lower()
    if n.startswith("bcmdhd_") or n.startswith("bcm4375") or n.startswith("nvram.txt_"):
        return "wifi_bt"
    if n.startswith("cs47l93") or n.startswith("cs35l40") or "audio_slsi" in n \
       or n in ("bidirmic.bin", "soundboosterparam.bin", "dax_param.bin",
                "default_configuration.hfd.cfg.json") or n.startswith("dual_cal_wide"):
        return "audio"
    if n.startswith("sec_s3nrn82"):
        return "nfc"
    if n.startswith("calliope"):
        return "modem_dsp"
    if n.startswith("fimc_is") or n.startswith("setfile_") or n in (
            "dnn.bin", "vts.bin", "fmsb.bin", "rxse.bin", "txse1.bin",
            "txse2.bin", "txse3.bin", "dual_cal_front_subfront.bin"):
        return "camera_isp"
    if n in ("mfc_fw.bin",):
        return "video"
    if n.startswith("npu") or n.startswith("iva30") or n.startswith("withlightfix") \
       or n in ("epx.bin", "usbin.bin", "usbout.bin", "score", "pp_cfg.json", "tracker_cfg.json"):
        return "npu"
    return "misc"

DESC = {
  "wifi_bt": "Broadcom BCM4375 Wi-Fi/BT firmware (Samsung bcmdhd driver)",
  "audio": "Cirrus CS47L93/CS35L40 audio DSP + Samsung SLSI audio",
  "nfc": "Samsung S3NRN82 NFC controller firmware",
  "modem_dsp": "Shannon/Calliope modem DSP image (Phase 7)",
  "camera_isp": "FIMC-IS camera ISP / sensor setfiles (Phase 7)",
  "video": "MFC video codec firmware",
  "npu": "NPU / AI accelerator firmware + models",
  "misc": "Other vendor firmware",
}

REQUIRED = {"wifi_bt", "audio"}  # Phase-1 bring-up needs WiFi/BT + audio blobs

def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()

def main():
    if not os.path.isdir(BLOBS):
        sys.stderr.write("no blobs dir: %s\nto ask the fetcher to populate it\n" % BLOBS)
        return 1
    entries = []
    for root, _, files in os.walk(BLOBS):
        for fn in sorted(files):
            if fn in ("sha256sums.txt",):
                continue
            full = os.path.join(root, fn)
            rel = os.path.relpath(full, BLOBS)
            entries.append((rel, full, fn))
    entries.sort()
    groups = {}
    for rel, full, fn in entries:
        cat = category(fn)
        groups.setdefault(cat, []).append((rel, full, fn))

    lines = []
    lines.append("# Nuxel S10+ firmware manifest — Samsung Galaxy S10+ (beyond2lte)")
    lines.append("#")
    lines.append("# AUTO-GENERATED by firmware/s10plus/gen-manifest.py from the blobs")
    lines.append("# fetched by firmware/s10plus/fetch-vendor-blobs.sh.")
    lines.append("#")
    lines.append("# Source of record: %s" % SRC)
    lines.append("#   (the pmaports vendor-blob source; matches the downstream")
    lines.append("#    kernel Linux4/android_kernel_samsung_exynos9820 4.14.253)")
    lines.append("#")
    lines.append("# WiFi is Samsung `bcmdhd` (NOT mainline brcmfmac). BT is `btbcm`")
    lines.append("# + the BCM4375 .hcd. All checksums are real sha256 values.")
    lines.append("#")
    lines.append("# Device: s10plus  codename: beyond2lte  soc: exynos9820")
    lines.append("# Flash method: heimdall (BOOT+SYSTEM) / TWRP adb+dd (no fastboot)")
    lines.append("")
    lines.append("device: s10plus")
    lines.append("codename: beyond2lte")
    lines.append("soc: exynos9820")
    lines.append("modem: shannon_lte")
    lines.append("flash_method: heimdall-bootimg")
    lines.append("provenance: %s" % SRC)
    lines.append("")
    lines.append("firmware_files:")
    # Downstream bcmdhd driver firmware paths (CONFIG_BCMDHD_FW_PATH etc.
    # in the kernel .config point at /etc/wifi/, NOT /lib/firmware).
    downstream = [
        ("vendor/firmware/bcmdhd_sta.bin_b1", "/etc/wifi/bcmdhd_sta.bin", "true",
         "bcmdhd station firmware (CONFIG_BCMDHD_FW_PATH)"),
        ("vendor/firmware/bcmdhd_mfg.bin_b1", "/etc/wifi/bcmdhd_mfg.bin", "false",
         "bcmdhd manufacturing firmware"),
        ("vendor/firmware/bcmdhd_mon.bin_b1", "/etc/wifi/bcmdhd_mon.bin", "false",
         "bcmdhd monitor firmware"),
        ("vendor/firmware/bcmdhd_clm.blob", "/etc/wifi/bcmdhd_clm.blob", "false",
         "bcmdhd CLM regulatory blob"),
        ("vendor/firmware/nvram.txt_CS01_semco_b1", "/etc/wifi/nvram_net.txt", "true",
         "bcmdhd NVRAM (replace with the rev matching YOUR unit)"),
    ]
    groups["wifi_bcmdhd_paths"] = [("__downstream__", None, d) for d in downstream]

    order = ["wifi_bt", "wifi_bcmdhd_paths", "audio", "nfc", "video", "camera_isp", "modem_dsp", "npu", "misc"]
    for cat in order:
        if cat not in groups:
            continue
        lines.append("  %s:" % cat)
        for rel, full, fn in sorted(groups[cat], key=lambda t: t[0]):
            if full is None:
                src, dest, req, desc = fn
                lines.append('    - source_path: "%s"' % src)
                lines.append('      dest: "%s"' % dest)
                lines.append('      description: "%s"' % desc)
                lines.append('      required: %s' % req)
                lines.append('      checksum: "%s"' % sha256(os.path.join(BLOBS, os.path.basename(src))))
                continue
            digest = sha256(full)
            req = "true" if cat in REQUIRED else "false"
            lines.append('    - source_path: "vendor/firmware/%s"' % rel)
            lines.append('      dest: "/lib/firmware/%s"' % rel)
            lines.append('      description: "%s"' % DESC.get(cat, cat))
            lines.append('      required: %s' % req)
            lines.append('      checksum: "%s"' % digest)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d blobs, %d groups)" % (OUT, len(entries), len(groups)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
