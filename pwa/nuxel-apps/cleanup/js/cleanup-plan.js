// Safe Cleanup planning engine — pure, allowlist-only, dry-run first.
//
// RULES, enforced here and asserted by tests/test-cleanup-plan.js:
//   1. Only paths in ALLOWLIST can ever be deleted.  Everything else found by a
//      scan is reported as SKIPPED with the reason, never deleted.
//   2. The dry run is computed from the live scan and reports the EXACT number of
//      bytes and files it would remove — not an estimate copied from a mock.
//   3. Execution requires a typed confirmation phrase.  There is no one-tap
//      delete and no "clean everything" button.
//   4. Deleting never touches package manager state, user documents, or anything
//      outside the allowlist; the tool can only remove files inside cache and log
//      directories, and only when they are regular files.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.CleanupPlan = factory();
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  var SCHEMA_VERSION = 1;
  var CONFIRM_PHRASE = 'DELETE CACHE';

  // kind: what the directory holds.  risk: what actually happens if it is removed.
  var ALLOWLIST = [
    { path: '/var/cache/nuxel', kind: 'application cache', risk: 'safe',
      consequence: 'Nuxel app caches are rebuilt on demand.' },
    { path: '/var/cache/pipewire', kind: 'audio server cache', risk: 'safe',
      consequence: 'PipeWire rebuilds its cache on next start.' },
    { path: '/var/cache/fontconfig', kind: 'font cache', risk: 'safe',
      consequence: 'Font cache is regenerated on next boot; the first launch may be slower.' },
    { path: '/var/tmp', kind: 'temporary files', risk: 'safe',
      consequence: 'Only regular files older than 3 days are removed.' },
    { path: '/var/log/journal', kind: 'systemd journal', risk: 'caution',
      consequence: 'Oldest journal entries are removed; recent logs are kept.' },
    { path: '/var/log/nuxel', kind: 'Nuxel service logs', risk: 'caution',
      consequence: 'Rotated Nuxel logs are removed; the active log file is kept.' },
    { path: '/home/nuxel/.cache/thumbnails', kind: 'thumbnail cache', risk: 'safe',
      consequence: 'Thumbnails are regenerated by the file manager.' },
    { path: '/home/nuxel/.cache/nuxel-pwa', kind: 'PWA web caches', risk: 'caution',
      consequence: 'Offline web caches are rebuilt on next app launch.' }
  ];

  var NEVER_TOUCH = [
    { pattern: '/home/nuxel/Documents, /home/nuxel/Downloads, /home/nuxel/Pictures, /home/nuxel/Music',
      reason: 'user data — never part of cleanup, not even in a "deep clean" mode' },
    { pattern: '/var/lib/nuxel', reason: 'persistent application state (permissions, notifications, registry)' },
    { pattern: '/var/lib/dnf and the RPM database', reason: 'package manager state — removing it breaks updates' },
    { pattern: '/etc/**', reason: 'system configuration' },
    { pattern: '/run/nuxel', reason: 'live runtime sockets, FIFOs and the console port lock' },
    { pattern: 'any block device (/dev/**, /dev/mmcblk*)', reason: 'the mission forbids writes to raw partitions entirely' }
  ];

  function formatBytes(n) {
    if (n === null || n === undefined) return '—';
    var u = ['B', 'KiB', 'MiB', 'GiB', 'TiB'], i = 0;
    while (n >= 1024 && i < u.length - 1) { n /= 1024; i++; }
    return (i ? n.toFixed(1) : String(n)) + ' ' + u[i];
  }

  function normalise(p) {
    var s = String(p || '').replace(/\/+$/, '');
    return s || '/';
  }

  function isAllowed(path) {
    var p = normalise(path);
    var hit = null;
    ALLOWLIST.forEach(function (a) { if (normalise(a.path) === p) hit = a; });
    return hit;
  }

  // Build the plan from a scan.  scan = { source, at, entries:[{path, bytes, files, newest?}] }
  function plan(scan) {
    var entries = (scan && scan.entries) || [];
    var allowed = [], skipped = [];
    entries.forEach(function (e) {
      var a = isAllowed(e.path);
      if (a) {
        allowed.push({ path: normalise(e.path), bytes: Number(e.bytes) || 0, files: Number(e.files) || 0,
                       kind: a.kind, risk: a.risk, consequence: a.consequence });
      } else {
        skipped.push({ path: e.path, bytes: Number(e.bytes) || 0, files: Number(e.files) || 0,
                       reason: 'not in the cleanup allowlist — never deleted by Safe Cleanup' });
      }
    });
    allowed.sort(function (a, b) { return (b.bytes - a.bytes) || (a.path < b.path ? -1 : 1); });
    var totalBytes = allowed.reduce(function (s, e) { return s + e.bytes; }, 0);
    var totalFiles = allowed.reduce(function (s, e) { return s + e.files; }, 0);
    return {
      schema_version: SCHEMA_VERSION,
      dryRun: true,
      source: (scan && scan.source) || 'unknown',
      scanned_at: (scan && scan.at) || null,
      allowlist_version: SCHEMA_VERSION,
      entries: allowed,
      skipped: skipped,
      totalBytes: totalBytes,
      totalFiles: totalFiles,
      reclaimable: formatBytes(totalBytes),
      blocked: skipped.length,
      confirmPhrase: CONFIRM_PHRASE,
      neverTouch: NEVER_TOUCH
    };
  }

  // The hard gate.  Returns {ok, reason}.  The typed phrase must match exactly
  // (case-insensitive, trimmed) AND the plan must contain something to delete.
  function gate(typed, planObj) {
    if (!planObj || !planObj.entries.length) return { ok: false, reason: 'nothing in the allowlist to clean' };
    if (String(typed || '').trim().toUpperCase() !== CONFIRM_PHRASE) {
      return { ok: false, reason: 'type "' + CONFIRM_PHRASE + '" exactly to enable the delete step' };
    }
    return { ok: true, reason: 'confirmation accepted' };
  }

  // Apply the delete results to the plan (pure): returns a summary object.
  // results: [{path, ok, bytes, files, error}]
  function applyDelete(planObj, results) {
    var freed = 0, failed = [], removed = [];
    (results || []).forEach(function (r) {
      if (!isAllowed(r.path)) {
        failed.push({ path: r.path, error: 'refused: path is outside the allowlist' });
        return;
      }
      if (r.ok) { freed += Number(r.bytes) || 0; removed.push({ path: normalise(r.path), bytes: Number(r.bytes) || 0 }); }
      else failed.push({ path: r.path, error: r.error || 'delete failed' });
    });
    return {
      freedBytes: freed, freed: formatBytes(freed), removed: removed, failed: failed,
      attempted: (results || []).length, at: null
    };
  }

  // Safety check used by both the UI and the test suite: no allowlisted path may
  // be a prefix of a protected path (and vice versa) in a way that would let a
  // recursive delete escape.
  function auditAllowlist() {
    var problems = [];
    ALLOWLIST.forEach(function (a) {
      var p = normalise(a.path);
      if (p === '/' || p === '/home' || p === '/var' || p === '/etc' || p === '/usr' || p === '/dev') {
        problems.push('allowlist entry is too broad: ' + p);
      }
      if (!/^(\/var\/cache\/|\/var\/tmp|\/var\/log\/|\/home\/nuxel\/\.cache\/)/.test(p)) {
        problems.push('allowlist entry is outside the permitted cache/log prefixes: ' + p);
      }
      NEVER_TOUCH.forEach(function (n) {
        n.pattern.split(',').forEach(function (pat) {
          var t = pat.trim();
          if (t.indexOf('*') !== -1) return;
          if (t && (p === normalise(t) || normalise(t).indexOf(p + '/') === 0)) {
            problems.push('allowlist entry ' + p + ' contains protected path ' + t);
          }
        });
      });
    });
    return problems;
  }

  return {
    SCHEMA_VERSION: SCHEMA_VERSION,
    ALLOWLIST: ALLOWLIST,
    NEVER_TOUCH: NEVER_TOUCH,
    CONFIRM_PHRASE: CONFIRM_PHRASE,
    isAllowed: isAllowed,
    plan: plan,
    gate: gate,
    applyDelete: applyDelete,
    auditAllowlist: auditAllowlist,
    formatBytes: formatBytes
  };
}));
